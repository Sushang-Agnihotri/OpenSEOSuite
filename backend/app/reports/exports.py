_FORMULA_PREFIX = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(value: Any) -> Any:
    """Neutralise spreadsheet formula injection: crawled text must never be executed by Excel/Sheets."""
    if isinstance(value, dict | list):
        value = json.dumps(value, ensure_ascii=False, default=str)
    if isinstance(value, str):
        if value.startswith(_FORMULA_PREFIX):
            value = "'" + value
        return value[:32000]
    return value


def to_csv(rows: list[dict], columns: list[str] | None = None) -> bytes:
    columns = columns or (list(rows[0].keys()) if rows else [])
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(columns)
    for r in rows:
        writer.writerow([safe_cell(r.get(c)) for c in columns])
    return ("﻿" + buf.getvalue()).encode("utf-8")


def to_xlsx(sheets: dict[str, list[dict]]) -> bytes:
    wb = Workbook()
    wb.remove(wb.active)
    head_fill = PatternFill("solid", fgColor="1F2937")
    for name, rows in sheets.items():
        ws = wb.create_sheet(title=name[:31])
        if not rows:
            ws.append(["No data"])
            continue
        columns = list(rows[0].keys())
        ws.append(columns)
        for cell in ws[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = head_fill
            cell.alignment = Alignment(vertical="center")
        for r in rows:
            ws.append([safe_cell(r.get(c)) for c in columns])
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions
        for i, col in enumerate(columns, 1):
            width = max([len(str(col))] + [len(str(r.get(col) or "")) for r in rows[:200]])
            ws.column_dimensions[get_column_letter(i)].width = max(10, min(70, width + 2))
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# --------------------------------------------------------------------------- PDF
_SEV_HEX = {"critical": "#B91C1C", "high": "#C2410C", "medium": "#A16207", "low": "#475569"}
_styles = getSampleStyleSheet()
_H1 = ParagraphStyle("H1x", parent=_styles["Title"], fontSize=22, leading=26, alignment=0, spaceAfter=6)
_H2 = ParagraphStyle("H2x", parent=_styles["Heading2"], fontSize=14, leading=18, spaceBefore=12, spaceAfter=6)
_H3 = ParagraphStyle("H3x", parent=_styles["Heading3"], fontSize=11, leading=14, spaceBefore=8, spaceAfter=3)
_P = ParagraphStyle("Px", parent=_styles["BodyText"], fontSize=9.5, leading=13)
_SMALL = ParagraphStyle("Sx", parent=_P, fontSize=8, leading=10.5, textColor=colors.HexColor("#475569"))
_CELL = ParagraphStyle("Cx", parent=_P, fontSize=8.5, leading=11)


def _p(text: Any, style=_P) -> Paragraph:
    return Paragraph(escape(str(text if text is not None else "")), style)


def _table(data: list[list], widths: list[float], header: bool = True) -> Table:
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("FONTSIZE", (0, 0), (-1, -1), 8.5), ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
             ("ROWBACKGROUNDS", (0, 1 if header else 0), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")])]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F2937")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                  ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")]
    t.setStyle(TableStyle(style))
    return t


def _footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#64748B"))
    canvas.drawString(18 * mm, 10 * mm, f"Generated by {APP_NAME}")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _build(story: list, title: str) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm, title=title)
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def audit_pdf(site_name: str, site_url: str, crawl: dict, issue_groups: list[dict]) -> bytes:
    """``crawl``: {id, finished_at, score, stats}; ``issue_groups``: [{rule_id, count, urls: [...]}]."""
    stats = crawl.get("stats") or {}
    sev = stats.get("issues_by_severity", {})
    W = A4[0] - 36 * mm
    story: list = [_p("Technical SEO Audit Report", _H1), _p(f"{site_name} - {site_url}", _P),
                   _p(f"Crawl #{crawl['id']} completed {crawl.get('finished_at') or 'n/a'} - report generated {datetime.now():%Y-%m-%d %H:%M}", _SMALL),
                   Spacer(1, 8)]
    score = crawl.get("score")
    verdict = ("n/a" if score is None else "Good" if score >= 85 else "Needs attention" if score >= 65 else "Poor")
    story.append(_table([
        ["SEO score", "URLs crawled", "Indexable pages", "Critical", "High", "Medium", "Low"],
        [f"{score if score is not None else 'n/a'} / 100 ({verdict})", stats.get("total_urls", 0), stats.get("indexable_pages", 0),
         sev.get("critical", 0), sev.get("high", 0), sev.get("medium", 0), sev.get("low", 0)],
    ], [W * 0.26, W * 0.14, W * 0.16, W * 0.11, W * 0.11, W * 0.11, W * 0.11]))
    story += [Spacer(1, 6), _p(
        "How to read this report: the score starts at 100 for every page and loses points for each problem found "
        "(critical 25, high 10, medium 4, low 1). The site score is the average page score minus penalties for "
        "site-wide problems. Fix critical and high issues first; they block crawling, indexing or user access.", _SMALL)]
    if stats.get("limit_reached"):
        story.append(_p("Note: the crawl stopped at its URL limit, so the site was only partly analysed.", _SMALL))

    story.append(_p("Crawl overview", _H2))
    sc = stats.get("status_classes", {})
    links = stats.get("links", {})
    red = stats.get("redirects", {})
    overview = [["Metric", "Value", "Metric", "Value"],
                ["HTML pages (200)", stats.get("html_pages", 0), "Non-indexable pages", stats.get("non_indexable_pages", 0)],
                ["2xx / 3xx responses", f"{sc.get('2xx', 0)} / {sc.get('3xx', 0)}", "4xx / 5xx / failed", f"{sc.get('4xx', 0)} / {sc.get('5xx', 0)} / {sc.get('error', 0)}"],
                ["Internal links", links.get("internal", 0), "Broken internal links", links.get("broken_internal", 0)],
                ["External links", links.get("external", 0), "Broken external links", links.get("broken_external", 0)],
                ["Redirects", red.get("total", 0), "Redirect chains / loops", f"{red.get('chains', 0)} / {red.get('loops', 0)}"],
                ["Average words per page", stats.get("avg_word_count", 0), "Average response time", f"{stats.get('avg_response_ms', 0)} ms"],
                ["Sitemap URLs", (stats.get("sitemap") or {}).get("url_count", 0), "Pages with structured data", (stats.get("schema") or {}).get("pages_with_schema", 0)]]
    story.append(_table(overview, [W * 0.3, W * 0.2, W * 0.3, W * 0.2]))

    story.append(_p("Issues by priority", _H2))
    order = {s: i for i, s in enumerate(SEVERITIES)}
    groups = sorted(issue_groups, key=lambda g: (order[RULES[g["rule_id"]].severity], -g["count"]))
    if not groups:
        story.append(_p("No issues were found in this crawl."))
    rows = [["Priority", "Issue", "Affected", "Recommended fix"]]
    for g in groups:
        r = RULES[g["rule_id"]]
        rows.append([Paragraph(f'<font color="{_SEV_HEX[r.severity]}"><b>{r.severity.upper()}</b></font>', _CELL),
                     _p(r.title, _CELL), g["count"], _p(r.fix, _CELL)])
    if len(rows) > 1:
        story.append(_table(rows, [W * 0.12, W * 0.3, W * 0.1, W * 0.48]))

    detail = [g for g in groups if RULES[g["rule_id"]].severity in ("critical", "high")]
    if detail:
        story += [PageBreak(), _p("Critical and high-priority issues in detail", _H2)]
        for g in detail:
            r = RULES[g["rule_id"]]
            story.append(_p(f"{r.title} ({g['count']} affected)", _H3))
            story.append(_p(r.description))
            story.append(Paragraph(f"<b>Fix:</b> {escape(r.fix)}", _P))
            for u in g.get("urls", [])[:15]:
                story.append(_p(f"- {u}", _SMALL))
            if g["count"] > 15:
                story.append(_p(f"... and {g['count'] - 15} more (see the CSV/Excel export for the full list)", _SMALL))
    return _build(story, f"SEO audit - {site_name}")


def competitor_pdf(comparison: dict) -> bytes:
    site = comparison["site"]
    W = A4[0] - 36 * mm
    story: list = [_p("Competitor Comparison Report", _H1), _p(f"{site['name']} - {site['url']}"),
                   _p(f"Generated {datetime.now():%Y-%m-%d %H:%M}", _SMALL), Spacer(1, 8)]
    cols = [("SEO score", "score"), ("URLs crawled", "urls_crawled"), ("Indexable pages", "indexable_pages"), ("Sitemap URLs", "sitemap_urls"),
            ("Avg words / page", "avg_word_count"), ("Avg title length", "avg_title_length"), ("Avg description length", "avg_description_length"),
            ("Pages w/o description", "pages_missing_description"), ("Avg internal links out", "avg_internal_links_out"),
            ("Avg H2 per page", "avg_h2_per_page"), ("Avg response (ms)", "avg_response_ms")]
    entities = [("Your site", site.get("profile"))] + [(c["name"], c.get("profile")) for c in comparison["competitors"]]
    entities = [(n, p) for n, p in entities if p][:5]
    if len(entities) < 2:
        story.append(_p("Crawl your site and at least one competitor to produce a comparison."))
        return _build(story, "Competitor comparison")
    rows = [["Metric (measured)"] + [_p(n, _CELL) for n, _ in entities]]
    for label, key in cols:
        rows.append([label] + [str(p.get(key, "n/a")) for _, p in entities])
    rows.append(["Critical / high issues"] + [f"{(p.get('issues_by_severity') or {}).get('critical', 0)} / {(p.get('issues_by_severity') or {}).get('high', 0)}" for _, p in entities])
    cw = (W - W * 0.28) / len(entities)
    story.append(_table(rows, [W * 0.28] + [cw] * len(entities)))
    for c in comparison["competitors"]:
        prof = c.get("profile") or {}
        ov = prof.get("keyword_overlap")
        if not ov:
            continue
        story.append(_p(f"{c['name']}: topical gaps and opportunities", _H2))
        story.append(_p(f"Shared title/H1 terms: {ov['shared_terms']} (overlap {round(ov['overlap_share'] * 100)}%). {ov['method']}", _SMALL))
        gaps = ", ".join(g["term"] for g in ov["gaps"][:40]) or "none found"
        story.append(Paragraph(f"<b>Topics they cover and you do not:</b> {escape(gaps)}", _P))
        opp = prof.get("content_opportunities") or []
        if opp:
            rows = [["Competitor page", "Topics you lack"]] + [[_p(f"{o['title']} - {o['url']}", _CELL), _p(", ".join(o["topics_you_lack"]), _CELL)] for o in opp[:12]]
            story += [Spacer(1, 4), _table(rows, [W * 0.6, W * 0.4])]
    story.append(Spacer(1, 10))
    for n in comparison.get("notes", []):
        story.append(_p(f"Note: {n}", _SMALL))
    return _build(story, "Competitor comparison")
